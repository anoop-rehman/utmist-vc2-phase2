"""Gate 2h's heterogeneous path: the per-creature design writer, and a
per-slot policy over a mixed team.

    MUJOCO_GL=osmesa PYTHONPATH=. .venv/bin/python \
        -m rower_soccer.competevo_port.gate_hetero [--steps 20]

`tests/test_design_parity.py` establishes the ANT's writer to machine epsilon
against CompetEvo's own emitted MJCF. There is no equivalent cross-stack
reference for the bug or the spider -- their driver only ever ran the ant --
so this file builds the reference the other way round: it bakes the genome into
the GEOMETRY of the scene XML and lets MuJoCo's compiler derive everything
else. That is exactly the split the writer has to get right, because the writer
computes in closed form what the compiler derives:

    written by the gate's reference XML   fromto, capsule radius, body pos, gear
    DERIVED by the compiler               body_mass, body_inertia, body_ipos,
                                          body_subtreemass, geom_pos,
                                          geom_rbound, geom_aabb, bvh_aabb,
                                          and (via mj_setConst) the three
                                          *_invweight0 / actuator_acc0 fields

so a writer whose per-creature capsule table, per-creature 0.3-vs-0.5 scale, or
inertia formula is wrong for the bug or the spider cannot agree with it.

The geometric half of the reference is not invented here either. Read against
`competevo/evo_envs/agents/dev_bug.py` and `dev_spider.py` (2026-08-26):
`set_design_params` computes `a = 1 + SCALE_MAX * s`, `b = 1 + 0.5 * SCALE_MAX
* s` and then, per leg L, multiplies body `L+1`'s geom `fromto` by `a[5L]`,
body `1(L+1)`'s `pos` by `a[5L]`, its geom `size` by `a[5L+1]` and `fromto` by
`a[5L+2]`, body `11(L+1)`'s `pos` by `a[5L+2]`, its `size` by `a[5L+3]` and
`fromto` by `a[5L+4]`, and the two motors' gears by `b[5L+1]` and `b[5L+3]`.
`SCALE_MAX` is 0.3 / 0.5 / 1.2 (the spider's is the one `creatures.py`
deliberately lowers to 0.5). `scaled_body_xml` / `scaled_motor_xml` below are
that, and nothing else -- which is why they read `spec.genome_table()` rather
than reimplement it, and why an error IN that table would be invisible to this
gate and has to be caught by reading their source, as above.

The reference scene is generated by `team_scene.dev_team_xml` ITSELF, with
`creatures.body_xml` / `motor_xml` temporarily swapped for scaled versions.
That is deliberate: body, geom and actuator ids, the contact bitmask, the
spawn poses and the goal assignment then come from the production code path, so
the two models differ in geometry and in nothing else, and the comparison is
index-for-index.

The checks
----------
  1. **Per creature, alone.** ant / bug / spider in a homogeneous 4-agent
     scene, random genomes, every written field against a fresh compile. Same
     1e-12 bar as `test_design_parity`, extended to `bvh_aabb` and the
     `mj_setConst` block.
  2. **Mixed scene, per-agent isolation.** Writing agent i's genome moves
     agent i's geoms, bodies and gears and NOTHING else. This is the check
     that catches the `_gather` padding trap: `_gather` returns 1.0 at a `-1`
     parameter index, so a padded row does not write nothing -- it writes the
     BASE capsule to whatever `geom_id` it names.
  3. **Negative control.** The same scene with `design.py`'s `*_keep` tensors
     disabled, which is precisely "pad the ragged tables the way `dev_env`
     pads its observation and hope". It must FAIL, and it must fail by
     corrupting a geom nobody's genome owns.
  4. **A max-scale ant beside a spider** reproduces a fresh compile of that ant
     genome, capsule by capsule -- the concrete case in which a padded write
     from the spider-width table would silently restore base geometry on the
     ant.
  5. **Compositions run.** Several mixed 4-agent scenes build, reset and step
     with finite observations, and a per-slot policy acts on them, is trained
     through the flat (minibatch) dispatch, and closes a `CoEvoPPO` iteration.
"""

